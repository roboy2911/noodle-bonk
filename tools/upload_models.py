"""Uploads every FBX in assets/models to Roblox as a Model asset, using Open Cloud.

Needs two environment variables:
    ROBLOX_API_KEY   an Open Cloud key with the "asset" read + write scope
    ROBLOX_USER_ID   the account that will own the models (your game's owner)

Run:  python3 tools/upload_models.py
      python3 tools/upload_models.py --force NoodleSegment   (re-upload one)

Already-uploaded files are skipped unless they changed (tracked by hash in
assets/models/uploaded.json). The asset IDs are written to
src/shared/ModelIds.luau for the game to load.
"""

import hashlib
import json
import os
import sys
import time
import urllib.error
import urllib.request
import uuid

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODELS = os.path.join(ROOT, "assets", "models")
LEDGER = os.path.join(MODELS, "uploaded.json")
LUAU_OUT = os.path.join(ROOT, "src", "shared", "ModelIds.luau")
API = "https://apis.roblox.com/assets/v1"

KEY = os.environ["ROBLOX_API_KEY"]
USER_ID = os.environ["ROBLOX_USER_ID"]


def request(method, url, body=None, headers=None):
    req = urllib.request.Request(url, data=body, method=method, headers={"x-api-key": KEY, **(headers or {})})
    for attempt in range(5):
        try:
            with urllib.request.urlopen(req, timeout=60) as response:
                return json.load(response)
        except urllib.error.HTTPError as err:
            detail = err.read().decode(errors="replace")[:500]
            if err.code in (429, 500, 502, 503) and attempt < 4:
                time.sleep(2 ** attempt * 2)
                continue
            raise RuntimeError(f"HTTP {err.code} for {url}: {detail}") from None


def multipart(fields, file_name, file_bytes, content_type):
    boundary = uuid.uuid4().hex
    parts = []
    for name, value in fields.items():
        parts.append(f"--{boundary}\r\nContent-Disposition: form-data; name=\"{name}\"\r\n\r\n{value}\r\n".encode())
    parts.append(
        f"--{boundary}\r\nContent-Disposition: form-data; name=\"fileContent\"; filename=\"{file_name}\"\r\n"
        f"Content-Type: {content_type}\r\n\r\n".encode()
    )
    parts.append(file_bytes)
    parts.append(f"\r\n--{boundary}--\r\n".encode())
    return b"".join(parts), f"multipart/form-data; boundary={boundary}"


def upload(name, path):
    with open(path, "rb") as f:
        data = f.read()
    meta = {
        "assetType": "Model",
        "displayName": f"Noodle Bonk - {name}",
        "description": "Noodle Bonk game model (made in Blender).",
        "creationContext": {"creator": {"userId": str(USER_ID)}},
    }
    body, content_type = multipart({"request": json.dumps(meta)}, os.path.basename(path), data, "model/fbx")
    op = request("POST", f"{API}/assets", body, {"Content-Type": content_type})
    op_path = op.get("path") or f"operations/{op.get('operationId')}"
    # Roblox processes the upload in the background; poll until done
    for _ in range(90):
        result = request("GET", f"{API}/{op_path}")
        if result.get("done"):
            if "error" in result:
                raise RuntimeError(f"{name}: upload failed: {result['error']}")
            return int(result["response"]["assetId"])
        time.sleep(2)
    raise RuntimeError(f"{name}: upload still processing after 3 minutes ({op_path})")


def write_luau(ledger):
    lines = [
        "--!strict",
        "-- AUTO-GENERATED by tools/upload_models.py. Don't edit by hand.",
        "-- Roblox asset IDs of the Blender models (Model assets owned by the game's creator).",
        "",
        "return {",
    ]
    for name in sorted(ledger):
        lines.append(f"\t{name} = {ledger[name]['assetId']},")
    lines.append("} :: { [string]: number }")
    with open(LUAU_OUT, "w") as f:
        f.write("\n".join(lines) + "\n")


def main():
    force = set(sys.argv[sys.argv.index("--force") + 1:]) if "--force" in sys.argv else set()
    ledger = json.load(open(LEDGER)) if os.path.exists(LEDGER) else {}
    files = sorted(f for f in os.listdir(MODELS) if f.endswith(".fbx"))
    for file in files:
        name = file[:-4]
        path = os.path.join(MODELS, file)
        digest = hashlib.sha256(open(path, "rb").read()).hexdigest()
        known = ledger.get(name)
        if known and known["sha256"] == digest and name not in force:
            print(f"skip   {name} (already uploaded as {known['assetId']})")
            continue
        asset_id = upload(name, path)
        ledger[name] = {"assetId": asset_id, "sha256": digest}
        json.dump(ledger, open(LEDGER, "w"), indent=2, sort_keys=True)
        print(f"upload {name} -> {asset_id}")
    write_luau(ledger)
    print(f"wrote {os.path.relpath(LUAU_OUT, ROOT)} with {len(ledger)} models")


if __name__ == "__main__":
    main()
