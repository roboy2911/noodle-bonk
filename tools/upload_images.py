"""Uploads the shop icons (marketing/shop/*.png) to Roblox as Image assets.

Same setup as upload_models.py (ROBLOX_API_KEY with asset write, ROBLOX_USER_ID).
Skips images already uploaded (by name + hash in marketing/shop/uploaded.json)
and writes the IDs to src/shared/ImageIds.luau for the in-game shop.

python3 tools/upload_images.py
"""

import hashlib
import json
import os
import time
import urllib.error
import urllib.request
import uuid

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FOLDER = os.path.join(ROOT, "marketing", "shop")
LEDGER = os.path.join(FOLDER, "uploaded.json")
LUAU_OUT = os.path.join(ROOT, "src", "shared", "ImageIds.luau")
API = "https://apis.roblox.com/assets/v1"
KEY = os.environ["ROBLOX_API_KEY"]
USER_ID = os.environ["ROBLOX_USER_ID"]


def call(method, url, body=None, headers=None):
    req = urllib.request.Request(url, data=body, method=method, headers={"x-api-key": KEY, **(headers or {})})
    for attempt in range(5):
        try:
            with urllib.request.urlopen(req, timeout=60) as r:
                return json.load(r)
        except urllib.error.HTTPError as err:
            if err.code in (429, 500, 502, 503) and attempt < 4:
                time.sleep(2 ** attempt * 2)
                continue
            raise RuntimeError(f"HTTP {err.code}: {err.read()[:300]}") from None


def upload(name, path):
    meta = {
        "assetType": "Image",
        "displayName": f"Noodle Bonk - {name}",
        "description": "Noodle Bonk shop icon",
        "creationContext": {"creator": {"userId": str(USER_ID)}},
    }
    boundary = uuid.uuid4().hex
    body = (
        f"--{boundary}\r\nContent-Disposition: form-data; name=\"request\"\r\n\r\n{json.dumps(meta)}\r\n"
        f"--{boundary}\r\nContent-Disposition: form-data; name=\"fileContent\"; filename=\"{name}.png\"\r\n"
        f"Content-Type: image/png\r\n\r\n"
    ).encode() + open(path, "rb").read() + f"\r\n--{boundary}--\r\n".encode()
    op = call("POST", f"{API}/assets", body, {"Content-Type": f"multipart/form-data; boundary={boundary}"})
    for _ in range(60):
        result = call("GET", f"{API}/{op['path']}")
        if result.get("done"):
            return int(result["response"]["assetId"])
        time.sleep(2)
    raise RuntimeError(f"{name}: still processing")


def main():
    ledger = json.load(open(LEDGER)) if os.path.exists(LEDGER) else {}
    for file in sorted(f for f in os.listdir(FOLDER) if f.endswith(".png")):
        name = file[:-4]
        digest = hashlib.sha256(open(os.path.join(FOLDER, file), "rb").read()).hexdigest()
        if name in ledger and ledger[name]["sha256"] == digest:
            print(f"skip   {name} ({ledger[name]['assetId']})")
            continue
        ledger[name] = {"assetId": upload(name, os.path.join(FOLDER, file)), "sha256": digest}
        json.dump(ledger, open(LEDGER, "w"), indent=2, sort_keys=True)
        print(f"upload {name} -> {ledger[name]['assetId']}")
    lines = ["--!strict", "-- AUTO-GENERATED by tools/upload_images.py. Don't edit by hand.", "-- Roblox image IDs of the shop icons.", "", "return {"]
    lines += [f"\t{name} = {ledger[name]['assetId']}," for name in sorted(ledger)]
    lines.append("} :: { [string]: number }")
    open(LUAU_OUT, "w").write("\n".join(lines) + "\n")
    print(f"wrote {os.path.relpath(LUAU_OUT, ROOT)}")


if __name__ == "__main__":
    main()
